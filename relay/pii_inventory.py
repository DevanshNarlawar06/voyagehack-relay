"""Generates `docs/pii-inventory.md` from skill manifests, so it cannot drift (PRD 14.1)."""

from __future__ import annotations

from pathlib import Path

from relay.config import ModelsConfig, get_config
from relay.skills.base import SKILLS_DIR, SkillManifest, load_manifest

_HEADER = """# PII inventory

Generated by `relay docs pii-inventory` from `definitions/skills/*.yaml` and `config/models.yaml` (PRD 14.1). Do not edit by hand. A test fails if this file drifts.

Raw documents and images never leave our infrastructure: OCR is local. Every outbound and inbound payload is stored masked in `model_payloads`, and the console's audit explorer shows the exact text.

## Known gap

**Free-text names and addresses are not masked yet.** Regex and checksum recognizers cover PAN, Aadhaar, IFSC, UAN, mobile, email, date of birth and labelled bank accounts. Names are masked only where a skill already knows them. Named-entity recognition (Presidio) is the planned fix (PRD 27.4). Do not send real personal data to a hosted provider until then.

## Models in use

| Tier | Model | Hosting region |
|---|---|---|
"""


def render(models: ModelsConfig, manifests: list[SkillManifest]) -> str:
    """Build the inventory's text."""
    lines = [_HEADER.rstrip("\n")]
    for tier in ("tier1", "tier2"):
        provider = models.provider_for_tier(tier)
        lines.append(f"| {tier} | `{provider.litellm_model}` | {provider.region} |")
    lines += ["", "## Skills", ""]
    for manifest in manifests:
        lines += [
            f"### {manifest.skill} (v{manifest.version})",
            "",
            manifest.description + ".",
            "",
            f"- **Fields it can send to a model:** {', '.join(manifest.data_seen)}",
            f"- **Masking:** {manifest.masking}",
            f"- **When a model is used:** {manifest.model_use}",
            f"- **Retention:** {manifest.retention}",
            "",
        ]
    return "\n".join(lines).rstrip("\n") + "\n"


def generate(directory: Path = SKILLS_DIR) -> str:
    """Render the inventory from the shipped manifests and models config."""
    names = sorted(path.stem for path in directory.glob("*.yaml"))
    return render(get_config().models, [load_manifest(name, directory) for name in names])
